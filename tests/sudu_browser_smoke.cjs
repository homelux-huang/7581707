const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1260,height:850}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/sudu/',{waitUntil:'domcontentloaded'});
 await page.waitForSelector('#sudu-controls-button');
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'true');
 await page.locator('#sudu-controls-button').click();
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false');
 await page.locator('#sudu-theme-button').click();
 assert.equal(await page.locator('html').getAttribute('data-sudu-theme'),'dark');
 await page.locator('#sudu-theme-button').click();
 assert.equal(await page.locator('html').getAttribute('data-sudu-theme'),'light');
 await page.locator('#sudu-controls-button').click();
 await page.locator('body').click({position:{x:3,y:400}});
 await page.locator('.option[data-answer]').first().click();
 await page.locator('#sudu-toggle-drag').click();
 await page.waitForSelector('#sudu-workspace .study-section');
 const before=await page.locator('#sudu-workspace .study-section').evaluateAll(xs=>xs.map(x=>x.dataset.block));
 assert(before.includes('question')&&before.includes('explanation')&&before.includes('source'));
 await page.locator('#sudu-workspace [data-block="source"] .sudu-move-up').click();
 const after=await page.locator('#sudu-workspace .study-section').evaluateAll(xs=>xs.map(x=>x.dataset.block));
 assert.notDeepEqual(after,before,'reorder should change');
 await page.reload({waitUntil:'domcontentloaded'});
 const pers=await page.locator('#sudu-toggle-drag').count();
 assert(pers===1);
 await page.locator('#sudu-toggle-drag').click();
 const afterReload=await page.locator('#sudu-workspace .study-section').evaluateAll(xs=>xs.map(x=>x.dataset.block));
 assert.deepEqual(afterReload,after);
 assert(!errors.length,'uncaught browser errors: '+errors.join(';'));
 const mobile=await browser.newPage({viewport:{width:375,height:780},isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto('http://127.0.0.1:8765/sudu/',{waitUntil:'domcontentloaded'});
 await mobile.locator('#sudu-controls-button').tap();
 assert.equal(await mobile.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false');
 const width=await mobile.evaluate(()=>({page:document.documentElement.scrollWidth,window:innerWidth}));
 assert(width.page<=width.window+3,'mobile horizontal overflow: '+JSON.stringify(width));
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 await page.waitForURL('**/sudu/');
 console.log('PASS: root redirect, RWD/mobile touch, dark/light, floating menu, persistent card layout, answered question');
 await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1)});
