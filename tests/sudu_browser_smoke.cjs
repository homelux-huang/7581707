const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1260,height:850}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/sudu/',{waitUntil:'domcontentloaded'});
 await page.waitForSelector('#sudu-controls-button');
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'true');
 await page.locator('#sudu-controls-button').click();
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false');
 const menuBackground=await page.locator('#sudu-floating-controls .floating-inner').evaluate(x=>getComputedStyle(x).backgroundColor);
 assert.equal(menuBackground,'rgb(16, 17, 19)','mega menu should use near-black background');
 assert.equal(await page.locator('#sudu-floating-controls .sudu-mega-col').count(),3,'exam/navigation/profile should be separated');
 await page.locator('#sudu-theme-button').click();
 assert.equal(await page.locator('html').getAttribute('data-sudu-theme'),'dark');
 await page.locator('#sudu-theme-button').click();
 assert.equal(await page.locator('html').getAttribute('data-sudu-theme'),'light');
 await page.locator('#sudu-controls-button').click();
 await page.locator('body').click({position:{x:3,y:400}});
 await page.locator('#sudu-controls-button').hover();
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false','desktop mouse hover should open');
 await page.mouse.move(3,400);
 await page.waitForTimeout(450);
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false','menu must remain open for first 450 ms');
 await page.waitForTimeout(850);
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'true','menu must close after ~1 second');
 await page.locator('#sudu-controls-button').hover();
 await page.mouse.move(3,400);
 await page.waitForTimeout(450);
 await page.locator('#sudu-controls-button').hover();
 await page.waitForTimeout(900);
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false','hover re-entry cancels delayed close');
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'true','Escape closes hovering menu');
 await page.locator('.option[data-answer]').first().click();
 await page.locator('.accounting-teacher').waitFor();
 await page.waitForTimeout(1300);
 const answerTop=await page.locator('#sudu-workspace [data-block="answer"]').evaluate(e=>e.getBoundingClientRect().top);
 assert(answerTop>=0&&answerTop<240,'answer should auto-scroll near viewport top, got '+answerTop);
 assert.equal(await page.locator('#sudu-return-to-question').isVisible(),true,'return-to-question shortcut visible');
 await page.locator('#sudu-return-to-question').click();
 await page.waitForTimeout(1200);
 const questionTop=await page.locator('#sudu-workspace [data-block="question"]').evaluate(e=>e.getBoundingClientRect().top);
 assert(questionTop>=0&&questionTop<200,'return shortcut should bring question to viewport, got '+questionTop);
 assert(await page.locator('.accounting-teacher').innerText().then(s=>s.includes('高職會計老師')&&s.includes('小學生白話')),'teacher note should display elementary explanation');
 assert(await page.locator('.accounting-teacher .concept-key').count()>0,'accounting keyword highlighted');
 await page.locator('#sudu-toggle-drag').click();
 await page.waitForSelector('#sudu-workspace .study-section');
 const before=await page.locator('#sudu-workspace .study-section').evaluateAll(xs=>xs.map(x=>x.dataset.block));
 assert(before.includes('question')&&before.includes('explanation')&&before.includes('source'));
 await page.locator('#sudu-workspace [data-block="source"] .sudu-move-up').click();
 const after=await page.locator('#sudu-workspace .study-section').evaluateAll(xs=>xs.map(x=>x.dataset.block));
 assert.notDeepEqual(after,before,'reorder should change');
 await page.reload({waitUntil:'domcontentloaded'});
 const pers=await page.locator('#sudu-toggle-drag').count();
 assert(pers===1);
 await page.locator('#sudu-toggle-drag').click();
 const afterReload=await page.locator('#sudu-workspace .study-section').evaluateAll(xs=>xs.map(x=>x.dataset.block));
 assert.deepEqual(afterReload,after);
 assert(!errors.length,'uncaught browser errors: '+errors.join(';'));
 const mobile=await browser.newPage({viewport:{width:375,height:780},isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto('http://127.0.0.1:8765/sudu/',{waitUntil:'domcontentloaded'});
 await mobile.locator('#sudu-controls-button').tap();
 assert.equal(await mobile.locator('#sudu-floating-controls').getAttribute('aria-hidden'),'false');
 const width=await mobile.evaluate(()=>({page:document.documentElement.scrollWidth,window:innerWidth}));
 assert(width.page<=width.window+3,'mobile horizontal overflow: '+JSON.stringify(width));
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 await page.waitForURL('**/sudu/');
 console.log('PASS: answer auto-scroll and return shortcut, delayed hover menu, teacher notes, mobile RWD, light/dark, persistence and direct entry');
 await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1)});
